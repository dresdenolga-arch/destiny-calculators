def element_balance_synthesis(elements: dict) -> str:
    """elements: {"Дерево": 4, "Огонь": 1.5, ...} -> applied 1-2 sentence synthesis."""
    if not elements:
        return ""
    ranked = sorted(elements.items(), key=lambda kv: kv[1])
    weakest_name, weakest_val = ranked[0]
    strongest_name, strongest_val = ranked[-1]
    if strongest_val == weakest_val:
        return "Стихии в карте распределены почти поровну — нет явного перекоса ни в одну сторону."

    strong_text = ELEMENT_TEXT.get(strongest_name, {}).get("much", "")
    weak_text = ELEMENT_TEXT.get(weakest_name, {}).get("little", "")
    parts = [f"Сильнее всего в карте выражена стихия {strongest_name} — {strong_text}."]
    if weakest_val < 1:
        parts.append(f"Меньше всего {weakest_name} — {weak_text}.")
    return " ".join(parts)
