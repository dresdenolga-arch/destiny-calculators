# jyotish_calc.py отдаёт знак лагны только на санскрите (SIGNS_SA) — эти списки
# в calc-скрипте идут параллельно индексами, дублируем сопоставление здесь.
_SANSKRIT_TO_RU = dict(zip(
    ["Меша", "Вришабха", "Митхуна", "Карка", "Симха", "Канья",
     "Тула", "Вришчика", "Дхану", "Макара", "Кумбха", "Мина"],
    LAGNA_TEXT.keys(),
))


def lagna_text(sign_ru: str) -> str:
    return LAGNA_TEXT.get(sign_ru, "")


def lagna_text_from_sanskrit(sign_sa: str) -> str:
    return LAGNA_TEXT.get(_SANSKRIT_TO_RU.get(sign_sa, ""), "")


def dasha_planet_text(planet: str) -> str:
    return DASHA_PLANET_TEXT.get(planet, "")
